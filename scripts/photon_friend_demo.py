"""Runs 5 canned scenarios through POST /photon/friend-reply (in process, real Claude model) and writes the
replies to docs/photon_friend_transcripts.md for human review.

Sends nothing to iMessage. The Nessie key is removed from this process. Each call goes through the spend
ledger in friend_reply. Usage:  .venv/bin/python scripts/photon_friend_demo.py
"""
import os
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import backend.settings  # noqa: F401  loads .env

for k in [k for k in os.environ if k.startswith("NESSIE")]:
    os.environ.pop(k)
os.environ["PHOTON_FRIEND_MODE"] = "1"
os.environ["IMESSAGE_AGENT_SECRET"] = os.environ.get("IMESSAGE_AGENT_SECRET") or "demo-local-secret"

from fastapi.testclient import TestClient

from backend import main
from backend.services import friend_reply

